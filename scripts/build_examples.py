#!/usr/bin/env python3
"""Assemble docs/data/examples.json for the page.

Four pairs are real held-out pairs from the corpus (winner shown as
draft B; the outcome note says which reply actually earned the delta).
Texts are trimmed at sentence boundaries for the page; the tool
re-scores whatever is in the boxes, so the verdict shown is always the
verdict for the visible text. Two pairs (short, marketing) are written
for this demo to show the out-of-domain warnings, and say so.
"""

import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PAIRS = {p["pair_id"]: p for p in
         (json.loads(l) for l in (ROOT / "data" / "pairs.jsonl").open())}
SENT = re.compile(r"[^.!?]+[.!?]+")
TOK = re.compile(r"[a-z0-9]+")


def trim(text: str, max_words: int) -> str:
    # The corpus stores Reddit text HTML-escaped (&gt; for a quote
    # marker). Examples are for reading, so unescape them for display;
    # the page re-scores whatever is shown, so the verdicts stay honest.
    text = html.unescape(text)
    if len(TOK.findall(text.lower())) <= max_words:
        return text.strip()
    out, n = [], 0
    for s in SENT.findall(text):
        w = len(TOK.findall(s.lower()))
        if out and n + w > max_words:
            break
        out.append(s)
        n += w
    return "".join(out).strip() or text[:1200].strip()


def mined(pid: str, label: str, note: str) -> dict:
    p = PAIRS[pid]
    op = (p["op_title"] + "\n\n" + p["op_body"]).strip()
    return {
        "id": pid, "label": label, "op": trim(op, 380),
        "a": trim(p["loser"], 300), "b": trim(p["winner"], 300),
        "note": note,
    }


EXAMPLES = [
    mined("p_3590", "A clear win (real pair)",
          "A real held-out pair. Draft B is the reply that actually earned the poster's delta; draft A did not."),
    mined("p_3519", "Links and numbers (real pair)",
          "A real held-out pair. Draft B is the reply that actually earned the poster's delta; draft A did not."),
    mined("p_3478", "Winning on length (real pair)",
          "A real held-out pair. Draft B earned the delta, and it is over twice as long as draft A: cut both to the same length (the equal-length score) and the model flips to A. Length was doing much of the work."),
    mined("p_3491", "Too close to call (real pair)",
          "A real held-out pair (draft B earned the delta), picked because the model finds almost nothing between them."),
    {
        "id": "short-synthetic", "label": "Two short replies (written for this demo)",
        "op": "CMV: Social media does more harm than good for teenagers.\n\nI keep reading about anxiety and comparison, and it seems obvious that the harm outweighs the good. Change my view.",
        "a": "Totally agree with the studies. It is clearly harmful and there is not much more to say about it honestly.",
        "b": "I used to think that too, but have you asked what teens actually use it for? For many it is how they reach friends they would never see otherwise.",
        "note": "Written for this demo. Both drafts are very short, so the tool warns that they sit outside what the model was trained on.",
    },
    {
        "id": "marketing-synthetic", "label": "Marketing copy (written for this demo)",
        "op": "",
        "a": "Introducing SwiftJuice Pro! Buy now and save big: for a limited time only, get 25% off with free trial included. Click here to order now, offer ends soon. Our lowest price ever, money back guarantee, risk free!",
        "b": "Meet SwiftJuice Pro, the quiet cold-press juicer for small kitchens. Order now during our sale and get the pulp container free. Subscribe today for recipes, tips and member deals. Shop now and taste the difference!",
        "note": "Written for this demo. This is sales copy, not a ChangeMyView argument, so the tool warns that its verdict here is a rough guess at best.",
    },
]

(ROOT / "docs" / "data" / "examples.json").write_text(
    json.dumps(EXAMPLES, indent=1) + "\n")
(ROOT / "docs" / "examples-data.js").write_text(
    "/* Generated by scripts/build_examples.py from docs/data/examples.json. Do not edit. */\n"
    "window.PERSUADE_EXAMPLES = " + json.dumps(EXAMPLES) + ";\n")
print("wrote", len(EXAMPLES), "examples")
